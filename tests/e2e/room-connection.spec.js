import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

const databaseFixture = await readFile(new URL('./firebase-fixture.js', import.meta.url), 'utf8');
const firebaseAuthFixture = await readFile(new URL('./firebase-auth-fixture.js', import.meta.url), 'utf8');

// Exercise the real App, hooks, Room, and React StrictMode with controlled SDK events.
for (const role of ['host', 'member']) {
  test(`${role}: connection recovery, chat and transient reactions`, async ({ page }, testInfo) => {
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => {
      if (['error', 'warning'].includes(message.type())) errors.push(message.text());
    });
    await page.route('**/*', async (route) => {
      const url = new URL(route.request().url());
      if (url.origin === 'http://127.0.0.1:5175') return route.continue();
      let body;
      if (url.pathname.endsWith('/firebase-database.js')) body = databaseFixture;
      else if (url.pathname.endsWith('/firebase-auth.js')) body = firebaseAuthFixture;
    else if (url.pathname.endsWith('/firebase-app.js')) body = 'export const initializeApp = () => ({});';
      else if (url.hostname === 'www.youtube.com') body = 'window.YT = {Player: function(){}}; window.onYouTubeIframeAPIReady?.();';
      else if (url.hostname === 'accounts.google.com') body = 'window.google = {accounts: {oauth2: {}}};';
      else throw new Error(`Unexpected external request to ${url.origin}`);
      return route.fulfill({ contentType: 'text/javascript', headers: { 'access-control-allow-origin': '*' }, body });
    });
    if (role === 'host' && !testInfo.project.name.endsWith('mobile')) await page.setViewportSize({ width: 1536, height: 1024 });
    await page.goto('/?room=ROOM_A');
    await page.evaluate(() => document.fonts.ready);
    await expect(page).toHaveTitle('Watch Party | Watch together');
    await expect(page.getByRole('heading', { name: 'Join Room' })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('home.png'), fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.getByPlaceholder('Enter your name').first().fill(role === 'host' ? 'Host' : 'Guest');
    await page.getByRole('button', { name: role === 'host' ? 'Create Room' : 'Join Room', exact: true }).click();
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(role === 'host' ? "Host's Room" : 'Friday movie');
    const status = page.getByRole('status', { name: 'Live room connection' });
    await expect(status).toContainText('Connecting');
    await page.evaluate(() => window.setTestConnection(true));
    await expect(status).toContainText('Connected');
    await expect.poll(() => page.getByRole('button', { name: 'Browse media', exact: true }).evaluate(node => node.getBoundingClientRect().bottom <= innerHeight), { timeout: 1500 }).toBe(true);
    await page.getByRole('tab', { name: 'Chat', exact: true }).click();
    const draft = page.getByLabel('Message', { exact: true });
    if (role === 'member') {
      await page.evaluate(() => window.seedTestMessages('ROOM_A'));
      const log = page.getByRole('log', { name: 'Recent messages' });
      await expect(log.locator('.chat-bubble')).toHaveCount(50);
      await expect(page.getByText('History 24', { exact: true })).toHaveCount(0);
      await expect(log.getByText('History 74', { exact: true })).toBeVisible();
    }
    await draft.fill('Ready for the movie');
    await page.evaluate(() => window.setTestConnection(false));
    await expect(status).toContainText('Reconnecting');
    await expect(status).toContainText('room updates may be out of date');
    await expect(draft).toHaveValue('Ready for the movie');
    await expect(draft).toBeFocused();
    await page.getByRole('tab', { name: 'Watch', exact: true }).click();
    await page.getByRole('button', { name: 'Reactions', exact: true }).click();
    await expect(page.getByRole('button', { name: 'React with Like' })).toBeDisabled();
    await page.getByRole('button', { name: 'Reactions', exact: true }).click();
    await page.getByRole('tab', { name: 'Chat', exact: true }).click();
    const box = await status.boundingBox();
    const viewport = page.viewportSize();
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(viewport.width);
    await page.screenshot({ path: testInfo.outputPath('reconnecting.png') });
    await page.evaluate(() => window.setTestConnection(true));
    await expect(status).toContainText('Connected');
    await expect(status).not.toContainText('out of date');
    await page.evaluate(() => window.rejectNextTestMessage());
    await draft.press('Enter');
    await expect(page.getByRole('alert')).toHaveText('Message not sent. Try again.');
    await expect(draft).toHaveValue('Ready for the movie');
    await expect(draft).toBeFocused();
    await expect(page.getByText('private database detail')).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Retry message' })).toBeEnabled();
    await page.screenshot({ path: testInfo.outputPath('chat-error.png'), fullPage: true });
    await draft.press('Enter');
    await expect(draft).toHaveValue('');
    await expect(page.getByRole('log', { name: 'Recent messages' }).getByText('Ready for the movie', { exact: true })).toBeVisible();
    await expect(page.getByText('Sent', { exact: true })).toBeVisible();
    await expect(page.getByRole('log', { name: 'Recent messages' }).getByText('Ready for the movie', { exact: true })).toHaveCount(1);
    await page.screenshot({ path: testInfo.outputPath('connected.png'), fullPage: true });
    await page.getByRole('tab', { name: 'Watch', exact: true }).click();
    const roomId = await page.locator('.room-identity p > span').first().textContent();
    const playbackBefore = await page.evaluate((id) => window.testPlaybackState(id), roomId);
    await page.evaluate((id) => window.seedTestReactions(id), roomId);
    const reactions = page.getByRole('log', { name: 'Live reactions' });
    await expect(reactions.locator('.reaction-chip')).toHaveCount(0);
    await page.getByRole('button', { name: 'Reactions', exact: true }).click();
    await page.getByRole('button', { name: 'React with Like' }).click();
    await expect(reactions.getByText('Like', { exact: true })).toBeVisible();
    await page.evaluate((id) => window.addTestPeerReaction(id), roomId);
    await expect(reactions.locator('.reaction-chip')).toHaveCount(2);
    await expect(reactions.getByText('Taylor', { exact: true })).toBeVisible();
    await expect(reactions.getByText('Old reaction')).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath('reactions.png'), fullPage: true });
    await page.evaluate((id) => window.addTestPeerReaction(id, '<img src=x onerror=alert(1)>'), roomId);
    await expect(reactions.getByText('<img src=x onerror=alert(1)>', { exact: true })).toBeVisible();
    await expect(reactions.locator('img')).toHaveCount(0);
    await expect(reactions.locator('.reaction-chip')).toHaveCount(0, { timeout: 8000 });
    await page.evaluate(() => window.rejectNextTestReaction());
    await page.getByRole('button', { name: 'Reactions', exact: true }).click();
    await page.getByRole('button', { name: 'React with Love' }).click();
    await expect(page.getByRole('alert')).toHaveText('Reaction not sent. Try again.');
    await expect(page.getByText('private reaction provider detail')).toHaveCount(0);
    await expect(page.getByRole('button', { name: 'Reactions', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: 'Reactions', exact: true }).click();
    await page.getByRole('button', { name: 'React with Love' }).click();
    await expect(reactions.getByText('Love', { exact: true })).toHaveCount(1);
    await expect(page.getByRole('alert')).toHaveCount(0);
    expect(await page.evaluate((id) => window.testPlaybackState(id), roomId)).toEqual(playbackBefore);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.evaluate(() => window.failTestConnection());
    await expect(status).toContainText('Refresh the page to try again');
    await expect(page.getByText('private fixture error')).toHaveCount(0);
    await expect(page.locator('vite-error-overlay')).toHaveCount(0);
    expect(errors).toEqual([]);
  });
}
