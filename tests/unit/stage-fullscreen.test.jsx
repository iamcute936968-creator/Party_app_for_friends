import { act, cleanup, renderHook } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { useStageFullscreen } from '../../src/hooks/useStageFullscreen';
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); delete document.fullscreenElement; delete document.exitFullscreen; document.body.innerHTML = ''; });
it('keeps an immersive fallback when native fullscreen is unavailable or denied', async () => {
  const element = document.createElement('div'); document.body.append(element);
  element.requestFullscreen = vi.fn().mockRejectedValue(new Error('denied'));
  const ref = { current: element };
  const { result } = renderHook(() => useStageFullscreen(ref, 'ROOM_A'));
  await act(async () => result.current.toggle());
  expect(result.current.active).toBe(true);
  expect(document.body.style.overflow).toBe('hidden');
  await act(async () => result.current.toggle());
  expect(result.current.active).toBe(false);
  expect(document.body.style.overflow).not.toBe('hidden');
});
it('switches to the immersive stage when a keyboard shrinks native fullscreen', async () => {
  const element = document.createElement('div');
  element.setAttribute('data-chat-open', 'true');
  const input = document.createElement('input'); element.append(input); document.body.append(element);
  const viewport = new EventTarget(); viewport.height = window.innerHeight; viewport.offsetTop = 0;
  vi.stubGlobal('visualViewport', viewport);
  let fullscreen = null;
  Object.defineProperty(document, 'fullscreenElement', { configurable: true, get: () => fullscreen });
  element.requestFullscreen = vi.fn(async () => { fullscreen = element; document.dispatchEvent(new Event('fullscreenchange')); });
  document.exitFullscreen = vi.fn(async () => { fullscreen = null; document.dispatchEvent(new Event('fullscreenchange')); });
  const ref = { current: element };
  const { result } = renderHook(() => useStageFullscreen(ref, 'ROOM_A'));
  await act(async () => result.current.toggle());
  input.focus();
  viewport.height = 320;
  await act(async () => viewport.dispatchEvent(new Event('resize')));
  expect(document.exitFullscreen).toHaveBeenCalledOnce();
  expect(result.current.active).toBe(true);
  expect(element.style.getPropertyValue('--stage-height')).toBe('320px');
  await act(async () => result.current.toggle());
  expect(result.current.active).toBe(false);
  vi.unstubAllGlobals();
});
